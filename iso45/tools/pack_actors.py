"""Pack the 45-degree character sprites (art-pack/sprites3d/out45/<name>/1x) into one atlas per character
   -> img/actors/<name>.png + js/actors_data.js (window.ACTORS = {name: {frames: {key: [x,y,w,h,ax,ay]}, ...}}).
   ax, ay = the ground origin (feet) inside the trimmed frame. The web-demo sprites are not touched.
   python3 tools/pack_actors.py"""
import os, json, glob, re
import numpy as np
from PIL import Image
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(HERE)
SRC = os.path.join(ROOT, "..", "art-pack", "sprites3d", "out45")
SETS = {"li_mo": ("li_mo", r"^(idle|walk)_"), "li_mo_umb": ("li_mo_actions", r"^(uidle|uwalk)_"),
        "vendor": ("vendor", r"^(idle|walk|cook)_"), "uncle": ("uncle", r"^(idle|walk)_"), "office": ("office", r"^(idle|walk)_"),
        "student": ("student", r"^(idle|walk)_"), "rider": ("rider", r"^(ride|stop)_")}
os.makedirs(os.path.join(ROOT, "img", "actors"), exist_ok=True)
out = {}
for name, (src, pat) in SETS.items():
    pal = json.load(open(os.path.join(SRC, src, "palette.json")))
    fx, fy = pal["foot_anchor_out"][0] / pal["scale"], pal["foot_anchor_out"][1] / pal["scale"]
    files = sorted(f for f in glob.glob(os.path.join(SRC, src, "1x", "*.png")) if re.match(pat, os.path.basename(f)) and re.match(r".*_\d+\.png$", f))
    ims = []
    for f in files:
        a = np.asarray(Image.open(f).convert("RGBA")); al = a[..., 3] > 0
        ys, xs = np.where(al); y0, y1, x0, x1 = ys.min(), ys.max() + 1, xs.min(), xs.max() + 1
        ims.append((os.path.basename(f)[:-4], a[y0:y1, x0:x1], fx - x0, fy - y0))
    W = 1024; x = y = sh = 0; pos = []
    for k, im, ax, ay in sorted(ims, key=lambda t: -t[1].shape[0]):
        h, w = im.shape[:2]
        if x + w + 1 > W: x = 0; y += sh + 1; sh = 0
        pos.append((k, im, ax, ay, x, y)); x += w + 1; sh = max(sh, h)
    H = y + sh; atlas = np.zeros((H, W, 4), np.uint8); frames = {}
    for k, im, ax, ay, px, py in pos:
        h, w = im.shape[:2]; atlas[py:py + h, px:px + w] = im; frames[k] = [px, py, w, h, round(ax, 1), round(ay, 1)]
    Image.fromarray(atlas).save(os.path.join(ROOT, "img", "actors", name + ".png"), optimize=True)
    clips = {}
    for k in frames:
        c, d, i = k.rsplit("_", 2); clips.setdefault(c, {}).setdefault(d, 0); clips[c][d] = max(clips[c][d], int(i) + 1)
    out[name] = {"img": f"img/actors/{name}.png", "frames": frames, "clips": {c: max(v.values()) for c, v in clips.items()},
                 "stride_m": pal.get("stride_out_px_per_cycle", 0) and round(pal["stride_out_px_per_cycle"] / pal["scale"] / 45.2548 * 1, 4),
                 "logical": pal["logical_size"]}
    print(name, len(frames), "frames", W, "x", H)
open(os.path.join(ROOT, "js", "actors_data.js"), "w").write("/* generated by tools/pack_actors.py from art-pack/sprites3d/out45 */\nwindow.ACTORS=" + json.dumps(out, separators=(",", ":")) + ";\n")
