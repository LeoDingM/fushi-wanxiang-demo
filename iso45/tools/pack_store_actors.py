"""Pack the 24便利店 staff-uniform sprites (art-pack/sprites3d/out45/{clerk_zhao,clerk_zhou,li_mo_uniform,li_mo_bar}, built with
   art-pack/sprites3d/build45.sh <name>.json - same rig/gait/palette as the street actors, outfit.apron = 店服绿围裙)
   -> img/actors/<name>.png + js/actors_store.js (merged into window.ACTORS; does not touch js/actors_data.js).
   Same packing as tools/pack_actors.py.   python3 tools/pack_store_actors.py"""
import os, json, re, sys, types
HERE = os.path.dirname(os.path.abspath(__file__))
src = open(os.path.join(HERE, "pack_actors.py")).read()
import re as _re
src = _re.sub(r"SETS = \{.*?\}\n(?=os\.makedirs)", "SETS = " + repr(dict({n: (n, r"^(idle|walk)_") for n in ("clerk_zhao", "clerk_zhou", "li_mo_uniform")}, li_mo_bar=("li_mo_bar", r"^eat_"))) + "\n", src, flags=_re.S)
src = src[:src.index('open(os.path.join(ROOT, "js", "actors_data.js")')]
g = {"__file__": os.path.join(HERE, "pack_actors.py")}; exec(compile(src, "pack_actors.py(store)", "exec"), g)
open(os.path.join(g["ROOT"], "js", "actors_store.js"), "w").write("/* generated by tools/pack_store_actors.py — 24便利店 staff uniforms; load after js/actors_data.js */\nwindow.ACTORS=Object.assign(window.ACTORS||{}," + json.dumps(g["out"], separators=(",", ":")) + ");\n")
