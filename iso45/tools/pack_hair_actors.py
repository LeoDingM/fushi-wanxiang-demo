"""Pack street hair/outfit NPC atlases from art-pack/sprites3d/out45/{woman_*,man_*}
   -> img/actors/<name>.png + js/actors_hair.js (Object.assign into window.ACTORS).
   Does NOT touch police/firefighter/nurse or actors_data.js.
   python3 tools/pack_hair_actors.py"""
import os, json, glob, re
import numpy as np
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SRC = os.path.join(ROOT, "..", "art-pack", "sprites3d", "out45")
ACT = os.path.join(ROOT, "img", "actors")
OUT_JS = os.path.join(ROOT, "js", "actors_hair.js")
os.makedirs(ACT, exist_ok=True)

NAMES = [
    "woman_bob", "woman_pony", "woman_long", "woman_pixie",
    "woman_twin", "woman_wave", "woman_bun", "woman_braid",
    "man_undercut", "man_buzz", "man_short", "man_messy",
    "man_sidepart", "man_mullet", "man_bald", "man_grey",
]
PAT = r"^(idle|walk)_"

out = {}
for name in NAMES:
    src = os.path.join(SRC, name)
    pal = json.load(open(os.path.join(src, "palette.json")))
    fx = pal["foot_anchor_out"][0] / pal["scale"]
    fy = pal["foot_anchor_out"][1] / pal["scale"]
    files = sorted(
        f for f in glob.glob(os.path.join(src, "1x", "*.png"))
        if re.match(PAT, os.path.basename(f)) and re.match(r".*_\d+\.png$", f)
    )
    ims = []
    for f in files:
        a = np.asarray(Image.open(f).convert("RGBA"))
        al = a[..., 3] > 0
        ys, xs = np.where(al)
        y0, y1, x0, x1 = ys.min(), ys.max() + 1, xs.min(), xs.max() + 1
        ims.append((os.path.basename(f)[:-4], a[y0:y1, x0:x1], fx - x0, fy - y0))
    W = 1024
    x = y = sh = 0
    pos = []
    for k, im, ax, ay in sorted(ims, key=lambda t: -t[1].shape[0]):
        h, w = im.shape[:2]
        if x + w + 1 > W:
            x = 0
            y += sh + 1
            sh = 0
        pos.append((k, im, ax, ay, x, y))
        x += w + 1
        sh = max(sh, h)
    H = y + sh
    atlas = np.zeros((H, W, 4), np.uint8)
    frames = {}
    for k, im, ax, ay, px, py in pos:
        h, w = im.shape[:2]
        atlas[py : py + h, px : px + w] = im
        frames[k] = [px, py, w, h, round(ax, 1), round(ay, 1)]
    Image.fromarray(atlas).save(os.path.join(ACT, name + ".png"), optimize=True)
    clips = {}
    for k in frames:
        c, d, i = k.rsplit("_", 2)
        clips.setdefault(c, {}).setdefault(d, 0)
        clips[c][d] = max(clips[c][d], int(i) + 1)
    # pull outfitId from source json if present
    cfg_path = os.path.join(ROOT, "..", "art-pack", "sprites3d", name + ".json")
    outfit_id = None
    if os.path.isfile(cfg_path):
        outfit_id = json.load(open(cfg_path)).get("outfitId")
    meta = {
        "img": f"img/actors/{name}.png",
        "frames": frames,
        "clips": {c: max(v.values()) for c, v in clips.items()},
        "stride_m": pal.get("stride_out_px_per_cycle", 0)
        and round(pal["stride_out_px_per_cycle"] / pal["scale"] / 45.2548 * 1, 4),
        "logical": pal["logical_size"],
        "hair_extra": True,
        "from_pipeline": "sprites3d/out45",
    }
    if outfit_id:
        meta["outfitId"] = outfit_id
    out[name] = meta
    print(name, len(frames), "frames", W, "x", H, outfit_id or "")

hdr = (
    "/* generated by tools/pack_hair_actors.py — street hair/outfit NPC atlases; "
    "load after js/actors_data.js; Char-C wires appearance.js */\n"
)
open(OUT_JS, "w").write(
    hdr + "window.ACTORS=Object.assign(window.ACTORS||{}," + json.dumps(out, separators=(",", ":")) + ");\n"
)
print("wrote", OUT_JS, "sets", len(out))
