"""rules.json -> rules.data.js (window.FUSHI_RULES_DATA) so pages opened from file:// can load the data without fetch."""
import json, os
H = os.path.dirname(os.path.abspath(__file__))
d = json.load(open(os.path.join(H, "rules.json"), encoding="utf-8"))
open(os.path.join(H, "rules.data.js"), "w", encoding="utf-8").write("/* generated by shared-rules/build.py from rules.json - edit the JSON */\nwindow.FUSHI_RULES_DATA=" + json.dumps(d, ensure_ascii=False, separators=(",", ":")) + ";\n")
print("rules.data.js", len(d["actions"]), "actions")
